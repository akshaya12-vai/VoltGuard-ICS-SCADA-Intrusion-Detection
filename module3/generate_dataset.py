"""Create the common 11 kV dataset.  python generate_dataset.py [--n 6000 --train-seed 1 --test-seed 2]
Writes data/feeder/{train,test,cleaned}.csv + reports/feeder_data_dictionary.csv + feeder_dataset_report.txt"""
import argparse
import os
from pathlib import Path
import pandas as pd
from simulate_process import simulate, PROCESS_COLS, TRAFFIC_COLS, ATTACKS

ROOT = Path(os.environ.get("VOLTGUARD_ROOT", Path(__file__).resolve().parent.parent))
DICT = [
    ("timestamp", "datetime", "Sample time, 1 Hz", "meta"),
    ("voltage_kv", "kV", "Line voltage, nominal 11 kV", "process"),
    ("current_a", "A", "Feeder current", "process"),
    ("frequency_hz", "Hz", "Grid frequency, nominal 50 Hz", "process"),
    ("power_mw", "MW", "Reported active power (should equal sqrt3*V*I*pf)", "process"),
    ("power_factor", "ratio", "Power factor", "process"),
    ("transformer_temp_c", "degC", "Transformer temperature", "process"),
    ("breaker_status", "0/1", "1 = closed, 0 = open", "process"),
    ("packets_per_s", "pkt/s", "Packets seen on the control network", "traffic (AI input)"),
    ("write_requests_per_s", "req/s", "Control write/command requests", "traffic (AI input)"),
    ("unique_src_ips", "count", "Distinct source addresses talking to the PLC", "traffic (AI input)"),
    ("avg_payload_bytes", "bytes", "Average payload size", "traffic (AI input)"),
    ("illegal_function_codes", "count", "Invalid protocol function codes", "traffic (AI input)"),
    ("true_attack", "0/1", "Ground truth label (1 = attack)", "label"),
    ("attack_type", "text", "normal / false_data_injection / breaker_manipulation / "
                            "replay_frozen_sensor / overvoltage_injection", "label"),
    ("ai_score", "0-1", "Module 2 output: attack probability (added by Module 2)", "module 2 output"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=6000)
    ap.add_argument("--train-seed", type=int, default=1)
    ap.add_argument("--test-seed", type=int, default=2)
    a = ap.parse_args()
    out = ROOT / "data/feeder"; out.mkdir(parents=True, exist_ok=True)
    (ROOT / "reports").mkdir(exist_ok=True)
    tr = simulate(a.n, a.train_seed, mock_ai=False, start="2026-10-13 08:00:00")
    te = simulate(a.n, a.test_seed, mock_ai=False, start="2026-10-14 08:00:00")
    tr.to_csv(out / "train.csv", index=False); te.to_csv(out / "test.csv", index=False)
    pd.concat([tr.assign(split="train"), te.assign(split="test")]).to_csv(out / "cleaned.csv", index=False)
    pd.DataFrame(DICT, columns=["column", "unit", "description", "role"]).to_csv(
        ROOT / "reports/feeder_data_dictionary.csv", index=False)
    rep = f"""VoltGuard common dataset: simulated 11 kV substation feeder
Generated by generate_dataset.py (offline simulation, no real plant data).
Rows: train {len(tr)} (seed {a.train_seed}), test {len(te)} (seed {a.test_seed}); 1 sample per second.
Attack share: train {tr.true_attack.mean():.1%}, test {te.true_attack.mean():.1%}
Attack types: {', '.join(ATTACKS)} (2-3 random windows each, 40-120 s).
No data leakage: splits use different seeds, so load phase, noise, attack timing and length all differ;
the test split is also on a different date.
Difficulty: benign maintenance bursts (15 per split) look like attacks on the network, false data injection
has almost no network signature, replay has a weak one. Network-only detection therefore cannot reach 100%.
Columns used by Module 2 (AI input): {', '.join(TRAFFIC_COLS)}
Columns kept for Module 3 (physics rules): {', '.join(PROCESS_COLS)}
Missing values: 0, duplicates: {int(tr.duplicated().sum() + te.duplicated().sum())}
"""
    (ROOT / "reports/feeder_dataset_report.txt").write_text(rep)
    print(rep)


if __name__ == "__main__":
    main()
